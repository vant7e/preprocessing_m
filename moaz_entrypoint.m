function moaz_entrypoint
cfg=struct('subject','subj04','session','S1', ...
    'bdf',getenv('MOAZ_BDF'),'letswave_root',getenv('MOAZ_LW_ROOT'), ...
    'output',getenv('MOAZ_OUTPUT'),'block_duration_s',291.1, ...
    'boundary_policy','drop_incomplete_with_audit', ...
    'remove_event_codes',[251 253 254 255 80],'manual_delete_event_indices',[]);
